// null when we can't tell how the exercise moves; better no drawing than a wrong one
export function sceneFor(name: string): Scene | null {
  const text = name.trim().toLowerCase();
  const key = BY_NAME[text] ?? BY_WORD.find(([pattern]) => pattern.test(text))?.[1];
  return key ? SCENES[key] : null;
}
